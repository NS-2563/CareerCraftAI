def generate_cold_email(name, role):

    return f"""
Subject: Application for {role}

Dear Recruiter,

My name is {name}. I recently completed my MCA and am actively seeking opportunities as a {role}.

I have experience in Python, Java, SQL, web development, and AI-based projects. I would appreciate the opportunity to discuss how my skills can contribute to your organization.

Thank you for your time and consideration.

Regards,
{name}
"""